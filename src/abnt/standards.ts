export function createDefaultFormatting(profileId = 'abnt_padrao', docType: DocumentTypeId = 'tcc'): AbntFormattingConfig {
  const profile = INSTITUTIONAL_PROFILES.find((p) => p.id === profileId) || INSTITUTIONAL_PROFILES[0];
  const spec = DOCUMENT_TYPE_SPECS[docType];
  return {
    fontFamily: profile.defaultFont,
    bodyFontSizePt: 12,
    quoteFontSizePt: 10,
    lineSpacing: 1.5,
    paragraphIndentCm: profile.paragraphIndentCm,
    quoteIndentCm: 4,
    marginsCm: { ...profile.marginsCm },
    justifyBody: true,
    uppercaseInTextParentheses: profile.uppercaseInTextParentheses,
    pageNumberPosition: 'top-right',
    startPageNumberOnFirstTextual: spec.startPageNumberOnFirstTextual,
    institutionalProfileId: profile.id,
    standardsVersionId: CURRENT_STANDARDS_VERSION,
  };
}
